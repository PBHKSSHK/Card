--      draft/rejected; give assigned team heads UPDATE on submitted lines so
--      per-line approve/reject actually works for non-admins.
--   3. HIGH  claim_attachments.line_id FK was ON DELETE CASCADE (code assumed
--      SET NULL) — editing a draft silently deleted line receipts. -> SET NULL.
--   4. HIGH  claim_batches_with_team_head view ran as owner (no security_invoker)
--      -> any user could read every colleague's claim. Make it respect RLS.
--   5. MED   claim_audit_log insert was WITH CHECK(true) (forgeable for any
--      batch). Limit to batches the actor is involved in.
--   6. MED   ns_departments.charge_to / entity_code / subsidiary columns were
--      never created by any migration (schema not reproducible). Add if missing.
--   7. MED   ns_intercompany_accounts write policy referenced non-existent
--      public.user_roles -> rebuild with public.is_super_user().
--   8. LOW   revoke anon EXECUTE re-granted on set_claim_batch_no; pin is_admin
--      search_path.

