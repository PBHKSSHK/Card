-- ============================================================
-- FIX 7 (MED) — ns_intercompany_accounts write policy (was referencing user_roles).
-- Guarded: this table is not present on every project (the intercompany feature
-- may not be deployed). Skip if absent so the rest of the migration still applies.
-- ============================================================
DO $$
BEGIN
  IF to_regclass('public.ns_intercompany_accounts') IS NOT NULL THEN
    EXECUTE 'DROP POLICY IF EXISTS "ic_accounts_write_admin" ON public.ns_intercompany_accounts';
    EXECUTE 'CREATE POLICY "ic_accounts_write_admin" ON public.ns_intercompany_accounts
               FOR ALL TO authenticated
               USING (public.is_super_user())
               WITH CHECK (public.is_super_user())';
    RAISE NOTICE 'Applied ic_accounts_write_admin policy';
  ELSE
    RAISE NOTICE 'Skipped: public.ns_intercompany_accounts does not exist (intercompany feature not deployed here)';
  END IF;
END $$;

-- ============================================================
-- FIX 8 (LOW) — undo anon EXECUTE re-grant; pin is_admin search_path
-- ============================================================
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_proc WHERE pronamespace = 'public'::regnamespace AND proname = 'set_claim_batch_no') THEN
    EXECUTE 'REVOKE EXECUTE ON FUNCTION public.set_claim_batch_no() FROM anon, public';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_proc WHERE pronamespace = 'public'::regnamespace AND proname = 'is_admin') THEN
    EXECUTE 'ALTER FUNCTION public.is_admin() SET search_path = public';
  END IF;
END $$;

